import 'package:flutter_test/flutter_test.dart';
import 'package:open_chat/src/calling/call_service.dart';

void main() {
  test('accepts per-call rooms generated by the server', () {
    expect(isValidCallRoom('call_${'a' * 32}'), isTrue);
    expect(isValidCallRoom('call_0123456789abcdef0123456789abcdef'), isTrue);
  });

  test('accepts legacy deterministic dm rooms', () {
    const a = '11111111-1111-1111-1111-111111111111';
    const b = '22222222-2222-2222-2222-222222222222';
    expect(isValidCallRoom('dm_${a}_$b'), isTrue);
  });

  test('rejects malformed room names', () {
    expect(isValidCallRoom(''), isFalse);
    expect(isValidCallRoom('call_short'), isFalse);
    expect(isValidCallRoom('room_${'a' * 32}'), isFalse);
    expect(isValidCallRoom('dm_not-a-uuid_not-a-uuid'), isFalse);
    expect(isValidCallRoom('x' * 200), isFalse);
  });
}
